package org.athletica.crm.core.subscription

import kotlinx.serialization.Serializable

/** Режим активации выданного абонемента; задаётся при выдаче. */
@Serializable
enum class ActivationMode {
    /** Сразу при выдаче; дата начала — дата выдачи. */
    IMMEDIATE,

    /** С указанной даты; она же дата начала. */
    ON_DATE,

    /** При первом посещении; дата начала — дата этого занятия. */
    ON_FIRST_VISIT,
}

/** Режим закрытия выданного абонемента; задаётся при выдаче. */
@Serializable
enum class CloseMode {
    /** Закрывает сотрудник. */
    MANUAL,

    /** Автоматически, когда списание делает остаток равным 0. */
    ON_LAST_SESSION,

    /** Автоматически на следующий день после даты окончания. */
    ON_EXPIRY,
}

/** Причина активации абонемента. */
@Serializable
enum class ActivationReason {
    /** При выдаче (режим «сразу» или «с даты» с наступившей датой). */
    ON_ISSUE,

    /** Фоном по наступлении даты активации. */
    ON_DATE,

    /** Фоном по наступлении крайней даты активации. */
    ON_DEADLINE,

    /** Первым посещением. */
    FIRST_VISIT,
}

/** Причина закрытия абонемента. */
@Serializable
enum class CloseReason {
    /** Закрыт сотрудником. */
    MANUAL,

    /** Закрыт списанием последнего занятия. */
    LAST_SESSION,

    /** Закрыт по истечении срока. */
    EXPIRY,
}

/** Положение даты относительно срока активного абонемента. */
@Serializable
enum class TermPosition {
    /** Дата раньше даты начала. */
    NOT_STARTED,

    /** Дата начала ≤ дата ≤ дата окончания. */
    IN_TERM,

    /** Дата позже даты окончания. */
    EXPIRED,
}

/** Причина признака «заканчивается» у активного абонемента. */
@Serializable
enum class EndingSoonReason {
    /** До даты окончания 7 дней или меньше. */
    BY_DATE,

    /** Остаток ровно одно занятие. */
    BY_SESSIONS,
}

/** Состояние текущей заморозки абонемента на дату организации. */
@Serializable
enum class FreezeStatus {
    /** Дата начала заморозки ещё не наступила; абонемент обычный активный. */
    SCHEDULED,

    /** Сегодня в периоде заморозки. */
    ACTIVE,
}

/** Основание снятия заморозки абонемента. */
@Serializable
enum class UnfreezeReason {
    /** Сотрудник отменил заморозку до её начала. */
    CANCELLED,

    /** Сотрудник разморозил абонемент досрочно. */
    MANUAL,

    /** Посещение в период заморозки. */
    VISIT,

    /** Период заморозки закончился. */
    EXPIRED,
}
